export function buildRetailerSearchUrl(retailerName, productName, rawSource = "") {
  const query = encodeURIComponent(String(productName || "").trim());
  const defaultStore = RETAILER_DEFAULTS[retailerName];
  if (defaultStore) {
    return `${defaultStore.searchBase}${query}`;
  }

  const extraBuilder = EXTRA_MERCHANT_SEARCH_URLS[retailerName];
  if (extraBuilder) {
    return extraBuilder(String(productName || "").trim());
  }

  const domainMatch = String(rawSource || "").match(
    /([a-z0-9-]+\.)+[a-z]{2,}/i
  );
  if (domainMatch) {
    return `https://${domainMatch[0].toLowerCase()}`;
  }

  return `https://www.nykaa.com/search/result/?q=${query}`;
}

function buildOffer({
  retailer,
  productName,
  price,
  originalPrice = null,
  inStock = true,
  stockLabel,
  shippingInfo,
  shippingCost = null,
  shippingDays = null,
  estimatedDelivery = null,
  storeRating = null,
}) {
  const resolvedDiscount =
    originalPrice && originalPrice > price
      ? Math.round(((originalPrice - price) / originalPrice) * 100)
      : null;

  const storeUrl = buildRetailerSearchUrl(retailer, productName);
  let linkHostname = RETAILER_DEFAULTS[retailer]?.hostname || "";
  if (!linkHostname && storeUrl) {
    try {
      linkHostname = new URL(storeUrl).hostname.replace(/^www\./, "");
    } catch {
      linkHostname = "";
    }
  }

  return {
    retailer,
    price,
    originalPrice,
    discountPercent: resolvedDiscount,
    currency: "INR",
    inStock,
    stockLabel: stockLabel || (inStock ? "In Stock" : "Out of Stock"),
    shippingInfo,
    shippingCost,
    shippingDays,
    estimatedDelivery: estimatedDelivery || shippingInfo,
    storeRating,
    verified: true,
    isTargetRetailer: TARGET_RETAILERS.includes(retailer),
    storeTag: "Curated Demo Baseline",
    dataSource: "CURATED_DEMO",
    variantMatchStatus: "exact",
    variant: productName,
    matchedTitle: productName,
    storeUrl,
    linkType: "retailer_search",
    linkStatusLabel: "Retailer Search Link (Demo)",
    linkHostname,
  };
}

